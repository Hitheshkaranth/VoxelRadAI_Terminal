"""Write app/src/landing/benchmarks.generated.ts from score.py output, so the landing page never carries hand-typed numbers.

  python benchmark/emit_landing.py

Every model is scored on the ChestX-Det held-out test split (111 films) with the same scorer. Skanda was read twice with
the same weights (run 2, best checkpoint), so its counts are the mean of both reads, with Wilson intervals at single-read n.
"""
from __future__ import annotations

import json
import math
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "app" / "src" / "landing" / "benchmarks.generated.ts"
MODELS = [
    ("skanda", "Skanda V1", ["results-skanda-manifest-cxd.jsonl", "results-skanda-r2-manifest-cxd.jsonl"]),
    ("medgemma", "MedGemma 27B", ["results-cxd.jsonl"]),
    ("maira", "MAIRA-2", ["results-maira2-cxd.jsonl"]),
]
FRACTION = re.compile(r"^\s*(.+?)\s+(\d+)/(\d+) \(")  # labels pad to 18 chars, so one space can remain
HEAD = {
    "Abnormal studies flagged as abnormal": "abnormal",
    "Normal studies called normal": "normals",
    "Localisation": "localised",
}


def run(file: str) -> dict[str, dict[str, tuple[int, int]]]:
    env = {**os.environ, "PYTHONIOENCODING": "utf-8", "MANIFEST": "manifest-cxd.json"}
    text = subprocess.run([sys.executable, "score.py", "final", file, "--split", "test"], cwd=HERE, env=env,
                          capture_output=True, text=True, encoding="utf-8").stdout
    out: dict[str, dict[str, tuple[int, int]]] = {"headline": {}, "sensitivity": {}, "precision": {}}
    section = None
    for line in text.splitlines():
        for prefix, key in HEAD.items():
            if line.startswith(prefix):
                k, n = re.search(r"(\d+)/(\d+)", line.split(":", 1)[1]).groups()
                out["headline"][key] = (int(k), int(n))
        if line.startswith("Per-class sensitivity"):
            section = "sensitivity"; continue
        if line.startswith("Precision: images"):
            section = "precision"; continue
        if line.startswith("Precision, finding-level") or not line.strip():
            section = None if line.startswith("Precision, finding") else section
            continue
        m = FRACTION.match(line)
        if section and m:
            label, k, n = m.group(1).strip(), int(m.group(2)), int(m.group(3))
            if label == "TOTAL":
                out["headline"]["rightType"] = (k, n)
            else:
                out[section][label] = (k, n)
    return out


def pool(runs):
    merged = {g: {} for g in runs[0]}
    for group in merged:
        keys = set().union(*(r[group].keys() for r in runs))
        for key in keys:
            parts = [r[group].get(key, (0, 0)) for r in runs]
            merged[group][key] = (sum(p[0] for p in parts), sum(p[1] for p in parts))
    return merged


def wilson(k: int, n: int) -> list[float]:
    if n == 0:
        return [0, 0, 0]
    z, p = 1.96, k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return [round(p * 100, 1), round(max(0, c - h) * 100, 1), round(min(1, c + h) * 100, 1)]


def shape(group, reads: int):
    """Mean per read. Two reads of the same films are not independent, so intervals use single-read n."""
    out = {}
    for key, (k, n) in sorted(group.items()):
        k, n = k / reads, n / reads
        w = wilson(k, n)
        out[key] = {"k": round(k, 1), "n": round(n, 1), "pct": w[0], "ci": w[1:]}
    return out


CARD = HERE.parent / "docs" / "benchmark-card.svg"


def run3_right_type() -> float:
    """Skanda V1 (run 3) chest X-ray 'right finding type', read from the committed benchmark card.

    Run 3's raw results are not in this repository, so this one figure comes from the card. Its columns are
    MedGemma, MedGemma + MAIRA-2, Skanda run 2, Skanda run 3; the first 'Right' label belongs to the chest X-ray block.
    """
    texts = [t.strip() for t in re.findall(r"<text[^>]*>([^<]+)</text>", CARD.read_text(encoding="utf-8"))]
    values = [t for t in texts[: texts.index("Right")] if re.fullmatch(r"[\d.]+", t)][-4:]
    return float(values[3])


def main() -> None:
    models = []
    for key, name, files in MODELS:
        data = pool([run(f) for f in files])
        models.append({"key": key, "name": name, "reads": len(files), "files": files,
                       **{g: shape(data[g], len(files)) for g in ("headline", "sensitivity", "precision")}})
    pct3 = run3_right_type()
    k3 = round(pct3 * 220 / 100, 1)
    lo, hi = wilson(k3, 220)[1:]
    models[0]["headline"]["rightType"] = {"k": k3, "n": 220.0, "pct": pct3, "ci": [lo, hi], "source": "run 3 · docs/benchmark-card.svg"}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by benchmark/emit_landing.py from score.py output. Do not edit by hand.\n"
        "// ChestX-Det held-out test split, 111 films, radiologist labels; Wilson 95% intervals.\n"
        f"export const benchmarks = {json.dumps(models, indent=2)} as const\n", encoding="utf-8")
    for m in models:
        print(m["name"], {k: f"{v['k']}/{v['n']} {v['pct']}% {v['ci']}" for k, v in m["headline"].items()})


if __name__ == "__main__":
    main()
