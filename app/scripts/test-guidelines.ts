import assert from 'node:assert/strict'
import { adrenal, birads, bosniak, fleischner, lungRads, recommendationSentence, tirads, tiradsLevel, tiradsPoints } from '../src/lib/guidelines.ts'

// Fleischner 2017: solid nodules by size band, single/multiple and risk; size rounds to the nearest mm.
const solid = (sizeMm: number, multiple = false, highRisk = false) => fleischner({ sizeMm, type: 'solid', multiple, highRisk }).recommendation
assert.match(solid(5), /<6 mm, low-risk patient: No routine follow-up$/)
assert.match(solid(5.4), /<6 mm/)
assert.match(solid(5.5), /6-8 mm/, '5.5 mm rounds to 6 mm')
assert.match(solid(5, false, true), /Optional CT at 12 months$/)
assert.match(solid(6), /CT at 6-12 months, then consider CT at 18-24 months$/)
assert.match(solid(8), /6-8 mm/)
assert.match(solid(8.4), /6-8 mm/, '8.4 mm rounds to 8 mm')
assert.match(solid(7, false, true), /CT at 6-12 months, then CT at 18-24 months$/)
assert.match(solid(9), />8 mm.*Consider CT at 3 months, PET\/CT, or tissue sampling$/)
assert.match(solid(9, false, true), /Consider CT at 3 months, PET\/CT, or tissue sampling$/)
assert.match(solid(4, true), /^Multiple solid nodules <6 mm, low-risk patient: No routine follow-up$/)
assert.match(solid(4, true, true), /Optional CT at 12 months$/)
assert.match(solid(7, true), /CT at 3-6 months, then consider CT at 18-24 months$/)
assert.match(solid(7, true, true), /CT at 3-6 months, then at 18-24 months$/)
assert.match(solid(12, true), /CT at 3-6 months, then consider CT at 18-24 months$/)
const sub = (type: 'ground-glass' | 'part-solid', sizeMm: number, multiple = false) => fleischner({ sizeMm, type, multiple, highRisk: true }).recommendation
assert.match(sub('ground-glass', 5), /^Single ground-glass nodule <6 mm: No routine follow-up$/)
assert.match(sub('ground-glass', 6), /≥6 mm: CT at 6-12 months to confirm persistence, then CT every 2 years until 5 years$/)
assert.match(sub('part-solid', 5), /No routine follow-up$/)
assert.match(sub('part-solid', 10), /CT at 3-6 months to confirm persistence; if unchanged and the solid component remains <6 mm, annual CT for 5 years$/)
assert.match(sub('ground-glass', 4, true), /CT at 3-6 months; if stable, consider CT at 2 and 4 years$/)
assert.match(sub('part-solid', 7, true), /based on the most suspicious nodule/)
assert.ok(fleischner({ sizeMm: 7, type: 'ground-glass', multiple: false, highRisk: false }).notes.some((n) => /aged 35/.test(n)))
assert.throws(() => fleischner({ sizeMm: -1, type: 'solid', multiple: false, highRisk: false }), /non-negative/)
assert.throws(() => fleischner({ sizeMm: Number.NaN, type: 'solid', multiple: false, highRisk: false }))

// Lung-RADS v2022: boundaries are exclusive upper limits on mean diameter (one decimal, no rounding).
const lr = (input: Parameters<typeof lungRads>[0]) => lungRads(input).category
assert.equal(lr({ type: 'solid', sizeMm: 5.9, status: 'baseline' }), 'Lung-RADS 2')
assert.equal(lr({ type: 'solid', sizeMm: 6, status: 'baseline' }), 'Lung-RADS 3')
assert.equal(lr({ type: 'solid', sizeMm: 7.9, status: 'baseline' }), 'Lung-RADS 3')
assert.equal(lr({ type: 'solid', sizeMm: 8, status: 'baseline' }), 'Lung-RADS 4A')
assert.equal(lr({ type: 'solid', sizeMm: 14.9, status: 'baseline' }), 'Lung-RADS 4A')
assert.equal(lr({ type: 'solid', sizeMm: 15, status: 'baseline' }), 'Lung-RADS 4B')
assert.equal(lr({ type: 'solid', sizeMm: 3.9, status: 'new' }), 'Lung-RADS 2')
assert.equal(lr({ type: 'solid', sizeMm: 4, status: 'new' }), 'Lung-RADS 3')
assert.equal(lr({ type: 'solid', sizeMm: 6, status: 'new' }), 'Lung-RADS 4A')
assert.equal(lr({ type: 'solid', sizeMm: 8, status: 'new' }), 'Lung-RADS 4B')
assert.equal(lr({ type: 'solid', sizeMm: 5, status: 'growing' }), 'Lung-RADS 4A')
assert.equal(lr({ type: 'solid', sizeMm: 8, status: 'growing' }), 'Lung-RADS 4B')
assert.equal(lr({ type: 'solid', sizeMm: 9, status: 'baseline', juxtapleural: true }), 'Lung-RADS 2')
assert.equal(lr({ type: 'solid', sizeMm: 10, status: 'baseline', juxtapleural: true }), 'Lung-RADS 4A')
assert.equal(lr({ type: 'part-solid', sizeMm: 5, solidMm: 2, status: 'baseline' }), 'Lung-RADS 2')
assert.equal(lr({ type: 'part-solid', sizeMm: 10, solidMm: 5.9, status: 'baseline' }), 'Lung-RADS 3')
assert.equal(lr({ type: 'part-solid', sizeMm: 10, solidMm: 6, status: 'baseline' }), 'Lung-RADS 4A')
assert.equal(lr({ type: 'part-solid', sizeMm: 12, solidMm: 8, status: 'baseline' }), 'Lung-RADS 4B')
assert.equal(lr({ type: 'part-solid', sizeMm: 5, solidMm: 2, status: 'new' }), 'Lung-RADS 3')
assert.equal(lr({ type: 'part-solid', sizeMm: 9, solidMm: 3, status: 'new' }), 'Lung-RADS 4A')
assert.equal(lr({ type: 'part-solid', sizeMm: 9, solidMm: 4, status: 'growing' }), 'Lung-RADS 4B')
assert.equal(lr({ type: 'ground-glass', sizeMm: 29.9, status: 'baseline' }), 'Lung-RADS 2')
assert.equal(lr({ type: 'ground-glass', sizeMm: 30, status: 'baseline' }), 'Lung-RADS 3')
assert.equal(lr({ type: 'ground-glass', sizeMm: 30, status: 'new' }), 'Lung-RADS 3')
assert.equal(lr({ type: 'ground-glass', sizeMm: 35, status: 'growing' }), 'Lung-RADS 2')
assert.match(lungRads({ type: 'solid', sizeMm: 7, status: 'baseline' }).recommendation, /LDCT in 6 months/)
assert.match(lungRads({ type: 'solid', sizeMm: 9, status: 'baseline' }).recommendation, /LDCT in 3 months/)
assert.match(lungRads({ type: 'solid', sizeMm: 20, status: 'baseline' }).recommendation, /diagnostic chest CT/)
assert.match(lungRads({ type: 'solid', sizeMm: 3, status: 'baseline' }).recommendation, /LDCT in 12 months/)
assert.throws(() => lungRads({ type: 'part-solid', sizeMm: 5, solidMm: 6, status: 'baseline' }), /cannot exceed/)

// ACR TI-RADS: points, levels and size thresholds (FNA / follow-up).
assert.equal(tiradsPoints({ composition: 'solid or almost completely solid', echogenicity: 'hypoechoic', shape: 'wider-than-tall', margin: 'smooth or ill-defined', foci: ['none or large comet-tail artifacts'] }), 4)
assert.equal(tiradsPoints({ composition: 'solid or almost completely solid', echogenicity: 'very hypoechoic', shape: 'taller-than-wide', margin: 'extra-thyroidal extension', foci: ['macrocalcifications', 'punctate echogenic foci', 'punctate echogenic foci'] }), 15, 'foci add, duplicates count once')
assert.equal(tiradsPoints({ composition: 'spongiform', echogenicity: 'anechoic', shape: 'wider-than-tall', margin: 'smooth or ill-defined', foci: [] }), 0)
assert.deepEqual([0, 1, 2, 3, 4, 6, 7, 12].map(tiradsLevel), [1, 2, 2, 3, 4, 4, 5, 5])
assert.equal(tirads(0, 3).recommendation, 'No FNA')
assert.equal(tirads(2, 5).recommendation, 'No FNA')
assert.match(tirads(3, 2.5).recommendation, /^FNA recommended/)
assert.match(tirads(3, 2.4).recommendation, /^Follow-up ultrasound at 1, 3 and 5 years/)
assert.match(tirads(3, 1.4).recommendation, /^No FNA or follow-up/)
assert.match(tirads(4, 1.5).recommendation, /^FNA recommended/)
assert.match(tirads(5, 1.4).recommendation, /^Follow-up ultrasound at 1, 2, 3 and 5 years/)
assert.match(tirads(6, 0.9).recommendation, /^No FNA or follow-up/)
assert.match(tirads(7, 1.0).recommendation, /^FNA recommended/)
assert.match(tirads(8, 0.5).recommendation, /^Follow-up ultrasound annually/)
assert.match(tirads(8, 0.4).recommendation, /^No FNA or follow-up/)
assert.match(tirads(5, 1).category!, /TR4 \(moderately suspicious\), 5 points/)

// Bosniak 2019, adrenal, BI-RADS wording.
assert.match(bosniak('IIF').recommendation, /6 and 12 months, then annually for 5 years/)
assert.match(bosniak('I').recommendation, /no follow-up/)
assert.match(bosniak('IV').category!, /enhancing nodules/)
assert.throws(() => bosniak('V' as never))
assert.match(adrenal({ sizeCm: 3, unenhancedHu: 8 }).recommendation, /lipid-rich adenoma; no further imaging/)
assert.match(adrenal({ sizeCm: 3, unenhancedHu: 10 }).recommendation, /≤10 HU/)
assert.match(adrenal({ sizeCm: 3, unenhancedHu: 11 }).recommendation, /^2-4 cm indeterminate/)
assert.match(adrenal({ sizeCm: 0.8 }).recommendation, /Under 1 cm/)
assert.match(adrenal({ sizeCm: 1.5 }).recommendation, /12-month follow-up/)
assert.match(adrenal({ sizeCm: 1.5, cancerHistory: true }).recommendation, /PET\/CT; consider biopsy/)
assert.match(adrenal({ sizeCm: 4 }).recommendation, /consider resection/)
assert.match(adrenal({ sizeCm: 5, cancerHistory: true }).recommendation, /PET\/CT or biopsy/)
assert.match(adrenal({ sizeCm: 3, stableOneYear: true }).recommendation, /Stable/)
assert.match(adrenal({ sizeCm: 6, macroscopicFat: true }).recommendation, /myelolipoma/)
assert.match(birads('3').recommendation, /6-month/)
assert.match(birads('4B').category!, />10% to ≤50%/)
assert.match(birads('0').recommendation, /Recall/)

// Inserted sentence carries category, recommendation and the source.
assert.equal(recommendationSentence(fleischner({ sizeMm: 7, type: 'solid', multiple: false, highRisk: false })),
  'Single solid nodule 6-8 mm, low-risk patient: CT at 6-12 months, then consider CT at 18-24 months (Fleischner Society 2017).')
assert.equal(recommendationSentence(lungRads({ type: 'solid', sizeMm: 7, status: 'baseline' })),
  'Lung-RADS 3. Probably benign: LDCT in 6 months (ACR Lung-RADS v2022).')
for (const result of [fleischner({ sizeMm: 7, type: 'solid', multiple: false, highRisk: false }), lungRads({ type: 'solid', sizeMm: 7, status: 'baseline' }), tirads(4, 1), bosniak('II'), adrenal({ sizeCm: 2 }), birads('5')]) {
  assert.ok(result.citation.length > 20 && result.source)
}
console.log('Guidelines: Fleischner 2017, Lung-RADS v2022, ACR TI-RADS, Bosniak 2019, ACR adrenal and BI-RADS thresholds and wording passed')
